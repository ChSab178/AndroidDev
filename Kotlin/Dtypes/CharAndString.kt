
fun main (){
// Char :
// A char takes 2 bytes -> 16 bits of space in memory.
// It only 1 character.
// The character must be written in the single quotes ('').
    val elem:Char='@'
    println(elem)

// String :
// A string takes 1 or 2 bytes per character depends on target platform that u are using .
// It can store as much characters/words or even sentences as u want.
// The string must be written in the double quotes ("").
    val str:String="Hammad Asghar"
    println(str)
}
