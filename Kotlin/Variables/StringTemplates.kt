fun main(){
    val age=18
    // To print the var we use $ before var name without any space.
 	println("My age is $age") // It will print the age that is 18

    // But if we have to add 1 in the println func then we use ${var_name expression}
    println("Next year I will be ${age + 1} years old.") // It will shows age 19
}
