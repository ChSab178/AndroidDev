// Val and Var :

fun main(){
  // Val :
  val name="Hammad"
  // val is like a const.It is a read-only memory.
  // In it we can't change value like
  // val name="Hammad"
  // name="Ammad" It will give an error.

  // Var
  // Var is like a normal variable. Here u can change the value.
  var Class=10
  Class=11 // Here we changed the value of the var Class.
  // But we can't add any random type value. Like if 1st value is INT then we must change the variable with INT val.
  println(name)
  println(Class)
}
